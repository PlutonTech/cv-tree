export const icon = name => `<i data-i="${name}">${svg(name)}</i>`;

export function hydrateIcons(root) {
  root.querySelectorAll("[data-i]").forEach(el => { if (!el.firstChild) el.innerHTML = svg(el.dataset.i); });
}
